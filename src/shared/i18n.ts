// navigator.language (both fall back to 'en' for anything non-Chinese).
export type Locale = 'zh' | 'en';

export function detectLocale(tag: string | undefined | null): Locale {
  return !!tag && tag.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

